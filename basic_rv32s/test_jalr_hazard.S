# ============================================================================
# JALR 数据冒险测试程序
#
# 测试场景：
# 1. JAL 写 ra，紧接着 JALR 读 ra（WB-ID 冒险）
# 2. ADDI 写寄存器，紧接着 JALR 读（WB-ID 冒险）
# 3. Load 写寄存器，紧接着 JALR 读（Load-Use 冒险）
# ============================================================================

.section .text
.globl _start

_start:
    # 初始化栈指针
    li sp, 0x10000

    # ========================================================================
    # 测试 1: JAL 写 ra，紧接着 JALR 读 ra（最常见的函数返回场景）
    # ========================================================================
test_jal_jalr:
    li t0, 0xAAAA0001        # 测试标记：进入 test_jal_jalr
    jal ra, func1            # ra = PC+4，跳转到 func1
    li t0, 0xAAAA0002        # 测试标记：从 func1 返回

    # ========================================================================
    # 测试 2: ADDI 写寄存器，紧接着 JALR 读（WB-ID 前递测试）
    # ========================================================================
test_addi_jalr:
    li t0, 0xBBBB0001        # 测试标记：进入 test_addi_jalr
    la t1, target1           # 加载目标地址
    jalr x0, t1, 0           # 跳转到 target1

target1:
    li t0, 0xBBBB0002        # 测试标记：到达 target1

    # ========================================================================
    # 测试 3: Load 写寄存器，紧接着 JALR 读（Load-Use 冒险测试）
    # ========================================================================
test_load_jalr:
    li t0, 0xCCCC0001        # 测试标记：进入 test_load_jalr
    la t1, target2_addr      # 加载地址表地址
    lw t2, 0(t1)             # 从内存加载跳转目标地址
    jalr x0, t2, 0           # 立即使用刚加载的地址跳转（应该 stall）

target2:
    li t0, 0xCCCC0002        # 测试标记：到达 target2

    # ========================================================================
    # 测试 4: 连续的 JALR 调用（压力测试）
    # ========================================================================
test_chain_jalr:
    li t0, 0xDDDD0001        # 测试标记
    la t1, chain1
    jalr ra, t1, 0           # 跳转到 chain1
    li t0, 0xDDDD0005        # 返回后的标记

    # 成功：写入成功标志
    li t0, 0xFFFF0000        # 全部测试通过标记
    j end_loop

# ============================================================================
# 函数定义
# ============================================================================

func1:
    li t1, 0xA001            # 函数内标记
    jalr x0, ra, 0           # 返回（使用刚刚写入的 ra）

chain1:
    li t0, 0xDDDD0002
    la t1, chain2
    jalr ra, t1, 0
    li t0, 0xDDDD0004
    jalr x0, ra, 0           # 返回

chain2:
    li t0, 0xDDDD0003
    jalr x0, ra, 0           # 返回

end_loop:
    j end_loop               # 无限循环

# ============================================================================
# 数据段
# ============================================================================
.section .data
.align 4
target2_addr:
    .word target2            # target2 的地址
